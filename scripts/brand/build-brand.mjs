#!/usr/bin/env node
/**
 * Builds every logo file from one source (the refined ChristLink mark + wordmark from the logo canvas):
 *   components/brand/logoArt.ts   path data for the in-app <Logo> components
 *   assets/brand/*.svg            vector masters (dark and light grounds)
 *   assets/*.png, public/brand/*  app icon, adaptive icon, splash, notification icon, favicon, web icons, email logo
 *
 *   node scripts/brand/build-brand.mjs scripts/brand/wordmark.json
 *
 * wordmark.json holds the wordmark as outlines (Playfair Display SemiBold + Montserrat Regular, converted with
 * fontTools by scripts/brand/wordmark.py), so no brand font ships in the app. PNGs are rendered with Playwright's
 * Chromium (installed in the dev container; not an app dependency).
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const require = createRequire(import.meta.url);

// Brand colors: one gold everywhere (the app's t.c.gold), ink and ivory from the app palette
const GOLD = '#C9A84C';
const IVORY = '#F6EFE3';
const INK = '#1C160E';
const GROUND = '#0E0C0A';

// The mark, in its original coordinates (viewBox 740 335 520 690)
const MARK = {
  viewBox: [740, 335, 520, 690],
  ring: 'M915 910L795 738A250 250 0 1 1 1205 738L1085 910C1075 900 1070 885 1070 870L1070 769A188 188 0 1 0 930 769L930 870C930 885 925 900 915 910Z',
  bar: 'M864 563H1134A12 12 0 0 1 1146 575V611A12 12 0 0 1 1134 623H864A12 12 0 0 1 852 611V575A12 12 0 0 1 864 563Z',
  stem: 'M970 457Q970 445 982 445L1018 445Q1030 445 1030 457L1030 880C1030 915 1050 932 1050 960A50 50 0 0 1 950 960C950 932 970 915 970 880Z',
};

const round = d => d.replace(/-?\d+\.\d+/g, n => String(Math.round(Number(n) * 10) / 10));

function load(file) {
  const w = JSON.parse(fs.readFileSync(file, 'utf8'));
  return { christ: round(w.christ), link: round(w.link), social: round(w.social), width: w.width, height: w.height };
}

/** SVG for the mark alone, cropped to its viewBox. */
function markSvg({ ring, height = 690, bg }) {
  const [x, y, w, h] = MARK.viewBox;
  const width = (height * w) / h;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${x} ${y} ${w} ${h}">${
    bg ? `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${bg}"/>` : ''
  }<path fill="${ring}" d="${MARK.ring}"/><path fill="${GOLD}" d="${MARK.bar}"/><path fill="${GOLD}" d="${MARK.stem}"/></svg>`;
}

/** Horizontal lockup: mark (150 wide) + 36 gap + wordmark, centered vertically. */
function lockupSvg(wm, { ink }) {
  const markH = 199;
  const markW = (markH * MARK.viewBox[2]) / MARK.viewBox[3];
  const gap = 36;
  const W = Math.ceil(markW + gap + wm.width);
  const ty = (markH - wm.height) / 2;
  const s = markH / MARK.viewBox[3];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${markH}" viewBox="0 0 ${W} ${markH}">
<g transform="scale(${s}) translate(${-MARK.viewBox[0]} ${-MARK.viewBox[1]})"><path fill="${ink}" d="${MARK.ring}"/><path fill="${GOLD}" d="${MARK.bar}"/><path fill="${GOLD}" d="${MARK.stem}"/></g>
<g transform="translate(${markW + gap} ${ty})"><path fill="${ink}" d="${wm.christ}"/><path fill="${GOLD}" d="${wm.link}"/><path fill="${GOLD}" d="${wm.social}"/></g>
</svg>`;
}

/** A square canvas with the mark centered at `markHeight` (fraction of the side), optionally on a ground color. */
function squareSvg({ side, markHeight, ring, bg, monochrome }) {
  const [x, y, w, h] = MARK.viewBox;
  const mh = side * markHeight;
  const mw = (mh * w) / h;
  const s = mh / h;
  const fill = monochrome ?? null;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${side}" height="${side}" viewBox="0 0 ${side} ${side}">${
    bg ? `<rect width="${side}" height="${side}" fill="${bg}"/>` : ''
  }<g transform="translate(${(side - mw) / 2} ${(side - mh) / 2}) scale(${s}) translate(${-x} ${-y})"><path fill="${fill ?? ring}" d="${MARK.ring}"/><path fill="${fill ?? GOLD}" d="${MARK.bar}"/><path fill="${fill ?? GOLD}" d="${MARK.stem}"/></g></svg>`;
}

/** Social preview image (1200×630): lockup centered on the warm black ground. */
function ogSvg(wm) {
  const inner = lockupSvg(wm, { ink: IVORY });
  const lw = Number(/width="(\d+)"/.exec(inner)[1]);
  const scale = 760 / lw;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630"><rect width="1200" height="630" fill="${GROUND}"/><g transform="translate(${(1200 - 760) / 2} ${(630 - 199 * scale) / 2}) scale(${scale})">${inner
    .replace(/<svg[^>]*>/, '')
    .replace('</svg>', '')}</g></svg>`;
}

function writeTs(wm) {
  const out = `// Generated by scripts/brand/build-brand.mjs — do not edit by hand.
/** The ChristLink mark (open ring + cross with a rounded tip), original coordinates. */
export const MARK = {
  viewBox: '${MARK.viewBox.join(' ')}',
  aspect: ${MARK.viewBox[2]} / ${MARK.viewBox[3]},
  ring: '${MARK.ring}',
  bar: '${MARK.bar}',
  stem: '${MARK.stem}',
} as const;

/** The wordmark as outlines: CHRIST (ink) LINK (gold) over SOCIAL (gold). */
export const WORDMARK = {
  width: ${wm.width},
  height: ${wm.height},
  christ: '${wm.christ}',
  link: '${wm.link}',
  social: '${wm.social}',
} as const;
`;
  fs.mkdirSync(path.join(ROOT, 'components/brand'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'components/brand/logoArt.ts'), out);
}

async function render(jobs) {
  const { chromium } = require('playwright');
  const browser = await chromium.launch();
  const page = await browser.newPage();
  for (const { svg, out, width, height } of jobs) {
    await page.setViewportSize({ width, height });
    await page.setContent(`<html><body style="margin:0;background:transparent">${svg.replace('<svg ', `<svg style="display:block;width:${width}px;height:${height}px" `)}</body></html>`);
    await page.screenshot({ path: path.join(ROOT, out), omitBackground: true, clip: { x: 0, y: 0, width, height } });
  }
  await browser.close();
}

async function main() {
  const wm = load(process.argv[2] ?? path.join(ROOT, 'scripts/brand/wordmark.json'));
  writeTs(wm);

  const brandDir = path.join(ROOT, 'assets/brand');
  fs.mkdirSync(brandDir, { recursive: true });
  const svgs = {
    'mark-on-dark.svg': markSvg({ ring: IVORY }),
    'mark-on-light.svg': markSvg({ ring: INK }),
    'lockup-on-dark.svg': lockupSvg(wm, { ink: IVORY }),
    'lockup-on-light.svg': lockupSvg(wm, { ink: INK }),
  };
  for (const [name, svg] of Object.entries(svgs)) fs.writeFileSync(path.join(brandDir, name), svg + '\n');

  fs.mkdirSync(path.join(ROOT, 'public/brand'), { recursive: true });
  const lockupLight = svgs['lockup-on-light.svg'];
  const lw = Number(/width="(\d+)"/.exec(lockupLight)[1]);
  await render([
    // iOS icon: opaque, mark at ~62% height on the warm black ground
    { svg: squareSvg({ side: 1024, markHeight: 0.62, ring: IVORY, bg: GROUND }), out: 'assets/icon.png', width: 1024, height: 1024 },
    // Android adaptive foreground: transparent, mark inside the 66% safe circle
    { svg: squareSvg({ side: 1024, markHeight: 0.5, ring: IVORY }), out: 'assets/adaptive-icon.png', width: 1024, height: 1024 },
    // Splash: transparent mark; app.json sets the ground color and size
    { svg: squareSvg({ side: 1024, markHeight: 0.9, ring: IVORY }), out: 'assets/splash.png', width: 1024, height: 1024 },
    // Android status-bar icon: white silhouette on transparent
    { svg: squareSvg({ side: 96, markHeight: 0.8, monochrome: '#FFFFFF' }), out: 'assets/notification-icon.png', width: 96, height: 96 },
    { svg: squareSvg({ side: 48, markHeight: 0.8, ring: IVORY, bg: GROUND }), out: 'assets/favicon.png', width: 48, height: 48 },
    { svg: squareSvg({ side: 180, markHeight: 0.62, ring: IVORY, bg: GROUND }), out: 'public/brand/apple-touch-icon.png', width: 180, height: 180 },
    { svg: squareSvg({ side: 512, markHeight: 0.62, ring: IVORY, bg: GROUND }), out: 'public/brand/icon-512.png', width: 512, height: 512 },
    { svg: ogSvg(wm), out: 'public/brand/og-image.png', width: 1200, height: 630 },
    // Email header: light ground (most mail clients), 2× for sharpness, shown at 240 px wide
    { svg: lockupLight, out: 'public/brand/logo-email.png', width: 480, height: Math.round((480 * 199) / lw) },
  ]);
  fs.copyFileSync(path.join(brandDir, 'mark-on-dark.svg'), path.join(ROOT, 'public/brand/mark.svg'));
  console.log('Brand files written.');
}

main();
